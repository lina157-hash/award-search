// Copies the page-reading functions of public/cxcal.js (the bookmarklet's parser, DOM hints and the sanitized
// diagnostics) into cxcal-page.js, so the runner evaluates exactly the same code inside Cathay's page and there is
// one source of truth. Run `node build.js` after editing public/cxcal.js; test/cxcal-store.test.js checks it is current.
const fs = require('node:fs');
const path = require('node:path');

const NAMES = ['parseCathayText', 'cxHints', 'cxRoot', 'cxDiag'];

function extract(src, name) {
  const start = src.indexOf(`  function ${name}(`);
  if (start < 0) throw new Error(`${name} not found in public/cxcal.js`);
  const end = src.indexOf('\n  }\n', start);
  return src.slice(start, end + 4).replace(/^  /gm, '');
}

function build() {
  const src = fs.readFileSync(path.join(__dirname, '..', '..', 'public', 'cxcal.js'), 'utf8');
  const code = NAMES.map((n) => extract(src, n)).join('\n');
  return `// Generated by build.js from public/cxcal.js (parseCathayText, cxHints, cxRoot, cxDiag). Do not edit: change\n// public/cxcal.js and run \`node build.js\`.\nmodule.exports = ${JSON.stringify(code)};\n`;
}

if (require.main === module) {
  fs.writeFileSync(path.join(__dirname, 'cxcal-page.js'), build());
  console.log('cxcal-page.js updated');
}

module.exports = { build };
